import 'server-only';
import { mkdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

/**
 * Маркер «ежесуточный обход за московские сутки завершён» (заказ владельца 18.11).
 *
 * ## Зачем он файл, а не строка в БД
 *
 * Схему менять нельзя без отдельного согласия владельца (#025), а строки-заготовки
 * под маркер в базе нет. Файл в каталоге состояния — дешевле и переживает деплой
 * (каталог вне релиз-директориев, как `MEDIA_ROOT`).
 *
 * ## Кто его пишет
 *
 * **Приложение — и только по факту завершения обхода.** Раньше маркер писал воркер сразу
 * по ответу роута, а роут отвечает сразу (обход идёт в фоне). Из-за этого обход, который
 * начался и умер (деплой убил процесс), считался сделанным — и сутки терялись: у части
 * аккаунтов не было строки леджера, их клетка вендора не сдвигалась, серия дней рвалась.
 *
 * Теперь: обход отработал → маркер записан → воркер больше не дёргает вендора. Обход умер →
 * маркера нет → воркер (раз в 30 минут) начинает обход заново; забор идемпотентен
 * (`claim_result = 2` на повторе), поэтому лишних очков не начисляется.
 *
 * ## Путь
 *
 * `~/.local/state/karman/daily-bonus-<московская-дата>.done`. Тот же путь у воркера
 * (`scripts/reminders-worker.mjs`): воркер едет в артефакт отдельным файлом и не может
 * импортировать код приложения — поэтому формула пути повторяется в двух местах, и это
 * единственное намеренное дублирование.
 */
export const SWEEP_STATE_DIR = join(homedir(), '.local', 'state', 'karman');

/** Помечает: обход за московские сутки `date` завершён. */
export function writeSweepMarker(date: string, dir = SWEEP_STATE_DIR): void {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `daily-bonus-${date}.done`), new Date().toISOString());
}

/** Путь маркера обхода (для совпадения с воркером). */
export function sweepMarkerPath(date: string, dir = SWEEP_STATE_DIR): string {
  return join(dir, `daily-bonus-${date}.done`);
}
