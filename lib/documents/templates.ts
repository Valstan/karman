/**
 * Шаблоны документов — ПОДСКАЗКА, а не схема.
 *
 * Выбрав «Паспорт РФ», человек получает готовый список названий полей и просто
 * вписывает значения; выбрав «Свой документ» — пустой лист и добавляет поля
 * сам. После создания шаблон нигде не хранится и ничего не ограничивает: поля
 * можно удалить, переименовать и дописать. Именно поэтому шаблоны живут в коде,
 * а не в таблице — таблица создавала бы иллюзию, что документ обязан ей
 * соответствовать, и первый же «а у меня в свидетельстве есть ещё одна графа»
 * упирался бы в миграцию.
 *
 * Ядро (название, номер, дата выдачи, действует до, кем выдан) — колонки
 * `documents_document`, его в `fields` НЕТ: шаблон перечисляет только
 * ДОПОЛНИТЕЛЬНЫЕ поля. До 2026-09-04 «Номер» и «Дата выдачи» стояли и в ядре,
 * и в списке полей — человек видел два поля «Номер» и заполнял оба.
 *
 * `category` — имя категории в `documents_documentcategory` (имена — как в боевой
 * БД: «Личные документы», «Транспорт», «Медицинские документы», «Образование»,
 * «Трудовые документы», «Недвижимость», «Финансовые документы», «Прочее»); по нему
 * форма подставляет категорию, а если такой в базе нет — берётся «Прочее».
 * До 2026-09-12 здесь стояли имена «Паспорт», «СНИЛС»…, которых в проде не было, и
 * каждый шаблон молча падал в «Прочее».
 */

export type DocumentTemplate = {
  id: string;
  label: string;
  /** Значение для колонки `document_type` (varchar(20) — длиннее не влезет). */
  documentType: string;
  /** Категория по имени (см. сид `scripts/bootstrap.sql`); нет — «Прочее». */
  category: string;
  /** Названия дополнительных полей в том порядке, в каком их спрашивают. */
  fields: readonly string[];
  /** Какие поля ядра прячем: у «Контактов» нет ни номера, ни «кем выдан». */
  coreless?: boolean;
};

