-- 0035_accounts_daily_bonus.sql — леджер ежесуточного забора бонусов MiniMax (заказ владельца 18.11).
--
-- РУКОПИСНАЯ миграция (KARMAN не гоняет drizzle-kit generate). Применяется на проде
-- через psql ДО деплоя: migration-guard в deploy-prod.yml останавливает деплой, пока
-- миграция не лежит в журнале schema_migrations.
--
-- ЗАЧЕМ. Пока очки дня забирал тот, кто первым взял аккаунт, «сколько у нас сегодня
-- очков» знал только сам потребитель, а серия дней подряд у аккаунта рвалась: не взял
-- аккаунт за сутки — клетка сдвинулась. Заказ владельца: «каждые сутки пройтись по всем
-- аккаунтам и активировать на них бонусы, записывать у себя, у кого сколько очков
-- сегодня активировалось, а потом в течение дня раздавать эти аккаунты по запросам, зная,
-- по сколько очков отдаётся».
--
-- ЧТО ХРАНИМ (одна строка на пару «аккаунт + московские сутки»):
--   - day_no      — клетка вендора из ответа `signin/claim` (1..7): настоящая серия;
--   - points      — сколько очков даёт сегодняшняя клетка (400 / 1000);
--   - remaining   — остаток по панели (сколько ещё не потрачено); NULL — не знаем;
--   - status      — статус клетки панели (2 — можно забрать, 3 — забрано);
--   - claim_result— 1: забрали мы, 2: уже было получено сегодня (идемпотентность);
--   - claim_id    — идентификатор забора вендора (один на сутки);
--   - expire_at   — до какого момента бонус жив (ответ вендора);
--   - handed_*    — кому и когда отдали аккаунт и сколько очков он нёс.
--
-- ИНВАРИАНТЫ:
--   - одна строка на аккаунт и сутки (UNIQUE) — забор идемпотентен, повтор не плодит строки;
--   - забор НЕ тратит очки: очки начисляются (claim) и тратятся работой рантайма,
--     поэтому `points` — это номинал клетки, а `remaining` — остаток;
--   - строка удаляется вместе с аккаунтом (ON DELETE CASCADE).

BEGIN;

CREATE TABLE IF NOT EXISTS accounts_daily_bonus (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           integer NOT NULL REFERENCES auth_user (id) ON DELETE CASCADE,
  account_id        bigint NOT NULL REFERENCES accounts_account (id) ON DELETE CASCADE,
  used_on           date NOT NULL,
  day_no            smallint NOT NULL DEFAULT 0,
  points            integer NOT NULL DEFAULT 0,
  remaining         integer,
  status            smallint NOT NULL DEFAULT 0,
  claim_result      smallint NOT NULL DEFAULT 0,
  claim_id          varchar(64),
  expire_at         timestamptz,
  claimed_at        timestamptz NOT NULL DEFAULT now(),
  checked_at        timestamptz NOT NULL DEFAULT now(),
  handed_to_project_id bigint REFERENCES accounts_project (id) ON DELETE SET NULL,
  handed_at         timestamptz,
  handed_points     integer,
  CONSTRAINT accounts_daily_bonus_account_day_uq UNIQUE (account_id, used_on)
);

CREATE INDEX IF NOT EXISTS accounts_daily_bonus_day_idx
  ON accounts_daily_bonus (used_on);

CREATE INDEX IF NOT EXISTS accounts_daily_bonus_handed_idx
  ON accounts_daily_bonus (handed_to_project_id)
  WHERE handed_at IS NOT NULL;

COMMIT;
