-- 0033_account_usage_source — метка «кто потратил аккаунт» в журнале активаций.
--
-- РУКОПИСНАЯ миграция (KARMAN не гоняет drizzle-kit generate). Применяется на проде
-- через psql ДО деплоя: migration-guard в deploy-prod.yml останавливает деплой,
-- пока миграция не лежит в журнале schema_migrations.
--
-- ЗАЧЕМ. Журнал активаций (`accounts_usage`) — одна строка на аккаунт на московские
-- сутки: кто активировал, на какой проект, сколько очков. Но «кто активировал» там
-- один: владелец кнопкой в панели ИЛИ проект по HTTP (`POST /api/minimax/activations`
-- от Сарафана). Заказ владельца 14.11: «в статистике отдельно учитывай расход
-- аккаунтов минимакса запросами с Сарафана — это не программирование, это сам проект
-- Сарафан тратит аккаунты на обработку постов из ВК. Это надо подсчитывать отдельно от
-- аккаунтов, которые я трачу на программирование, и по дням смотреть, в какие дни по
-- сколько аккаунтов и очков тратится на Сарафане».
--
-- Различать по имени проекта нельзя: у владельца свой проект «САРАФАН» (кириллица —
-- программирование кода проекта), а журнальный проект комнаты зовётся «SARAFAN»
-- (латиница). Разница в одном символе — не различие, а ловушка.
--
-- ИНВАРИАНТЫ:
--   - source ∈ {'owner', 'api'}; 'owner' — активация кнопкой владельца (значение по
--     умолчанию, поэтому старые строки остаются 'owner' и правки истории не нужны);
--     'api' — активация по запросу проекта;
--   - метка НЕ стирается: если строку дня переписал владелец (например, поправил
--     номер клетки), source остаётся 'api' — расход проекта не должен потеряться.

BEGIN;

ALTER TABLE accounts_usage
  ADD COLUMN IF NOT EXISTS source varchar(16) NOT NULL DEFAULT 'owner';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'accounts_usage_source_range'
  ) THEN
    ALTER TABLE accounts_usage
      ADD CONSTRAINT accounts_usage_source_range
      CHECK (source IN ('owner', 'api'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS accounts_usage_source_idx
  ON accounts_usage (user_id, source, used_on);

COMMIT;
