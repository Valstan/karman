-- Слияние пар «начитка + план» (заказ владельца 24.11).
--
-- Задача в хранилище промтов теперь лежит ОДНИМ промтом: тело начитки, пустая
-- строка, тело плана. Чтобы правила «у этого промта уже есть план» и «план с
-- id N влит в промт M» проверялись без догадок по тексту, ведём таблицу
-- слияний: правило хранения должно быть проверяемым, а не угадываемым.
--
-- part_id — id слитой записи (плана или продолжения задачи). Сама строка плана
-- после слияния удаляется, поэтому внешнего ключа на part_id нет; на prompt_id
-- (промт-начитка, где теперь живёт этот текст) — есть.
--
-- Историческая забравка: пары, слитые 24.11 (скрипт scripts/merge_prompt_plans.sql).
-- На пустой базе (тесты) вставка не срабатывает: целевых промтов ещё нет.

CREATE TABLE IF NOT EXISTS prompt_part (
  part_id bigint PRIMARY KEY,
  prompt_id bigint NOT NULL REFERENCES prompt(id) ON DELETE CASCADE,
  merged_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS prompt_part_prompt_idx ON prompt_part (prompt_id);

