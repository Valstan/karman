-- 0019_session_epoch - поколение сессии (аудит #057, находка R2, high).
--
-- Зачем. Сессия - статeless JWT в cookie: в payload только uid и mfa, серверного
-- состояния нет, поэтому выданный токен нечем отозвать. TTL 14 дней, и НИЧТО в
-- приложении не прерывает это окно: смена пароля (своя и сбросом суперпользователем)
-- пишет только auth_user.password, к чему проверка подписи отношения не имеет.
-- Деактивация учётки сессию убивает, но владельцу запрещено деактивировать самого себя
-- ("нельзя отключить собственный аккаунт"), то есть у суперпользователя не было
-- kill-switch вообще. Украденная cookie суперпользователя с mfa:true - это 14 дней
-- полного доступа к vault и персональным данным, и отозвать их нечем.
--
-- Лечение. Счётчик поколений рядом с учёткой: значение кладётся в токен при выдаче и
-- сверяется при каждом запросе. Смена любого элемента безопасности увеличивает счётчик,
-- и все ранее выданные токены перестают проходить проверку. Обратная сторона одна и
-- ожидаемая: смена пароля разлогинивает ВСЕ сессии, включая текущую, поэтому операция
-- перевыпускает cookie текущему браузеру - см. rotateSessionCookie.
--
-- Совместимость. Токены, выданные ДО миграции, не несут epoch и будут отвергнуты как
-- «поколение не совпало». Это осознанный разлогин всех устройств: обратная совместимость
-- означала бы, что механизм отзыва начинает работать с какого-то момента в будущем, а
-- старое окно в 14 дней остаётся открытым именно там, где оно опаснее всего. Данные не
-- теряются, вход по паролю (+2FA) работает как раньше.

ALTER TABLE auth_user ADD COLUMN session_epoch integer NOT NULL DEFAULT 0;