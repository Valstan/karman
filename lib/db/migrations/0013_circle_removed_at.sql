-- Исправление утечки, найденной адверсариальным разбором 2026-09-04.
--
-- Дефект: исключение владельцем и добровольный выход писались в ОДНУ колонку
-- `left_at`, а `consented_at` при этом оставалось непустым. Интерфейс показывал
-- исключённому блок «Вы вышли из этого круга» с кнопкой «Вернуться», и она
-- работала: `respondToInvite` обновлял строку по условию «мой круг, мой
-- user_id», ничего больше не проверяя. Исключённый возвращал себе доступ ко
-- всем паспортным данным, СНИЛС, ИНН, адресам и сканам круга одним нажатием,
-- владелец об этом не узнавал, а исключить повторно означало войти в цикл,
-- который владелец всегда проигрывает.
--
-- Причина класса: два РАЗНЫХ события (моё решение уйти и чужое решение меня
-- убрать) писались одной меткой. Отличить их потом было нечем — в том числе
-- принципиально: в строке не осталось следа, кто её проставил.

alter table circle_member
  add column if not exists removed_at timestamptz;

comment on column circle_member.removed_at is
  'Исключён владельцем круга. Отличается от left_at (ушёл сам) намеренно: из этого состояния человек не возвращается по своей воле — только по новому приглашению владельца.';
