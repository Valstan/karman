-- 0029_accounts_activation_index — номер активации в неделе (заказ владельца 07.11).
--
-- РУКОПИСНАЯ миграция (KARMAN не гоняет drizzle-kit generate). Применяется на проде
-- через psql ДО деплоя: migration-guard в deploy-prod.yml блокирует авто-деплой
-- для коммита с миграцией (лечение — журнал schema_migrations, см. тех-долг).
--
-- ЗАЧЕМ. Неделя у аккаунта СВОЯ, а не общая: окно MiniMax начинается с ПЕРВОГО
-- использования аккаунта и длится 7 дней (документация M Plan, «用量说明»: «两个
-- 窗口都从首次使用时开始计时…周窗口持续 7 天»). Очки за активацию задаются её
-- номером внутри этого цикла: 4-я и 7-я — 1000, остальные — 400 (раздел
-- «每日签到»). Значит журналу надо помнить НОМЕР, а не только «был ли чек-ин в
-- этот день».
--
-- NULL = номер неизвестен (строки, записанные до этой миграции): тогда счёт
-- недельной квоты идёт по числу строк журнала — это оценка, и владелец может
-- уточнить номер руками при активации (в программе это поле выбора).
--
-- ИНВАРИАНТЫ:
--   - номер в пределах 1..7 (недельная квота аккаунта — семь активаций);
--   - дневная уникальность аккаунта (accounts_usage_account_day_uq) ОСТАЁТСЯ:
--     чек-ин в сутки один, и журнал держит одну строку на аккаунт на день.
--     Окно простоя сокращено до 6 часов (07.11), но это окно не сессии, а
--     простоя: повторная активация того же аккаунта в те же сутки обновляет
--     строку дня, а не создаёт вторую.

BEGIN;

ALTER TABLE accounts_usage
  ADD COLUMN IF NOT EXISTS activation_index smallint;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'accounts_usage_activation_index_range'
  ) THEN
    ALTER TABLE accounts_usage
      ADD CONSTRAINT accounts_usage_activation_index_range
      CHECK (activation_index IS NULL OR activation_index BETWEEN 1 AND 7);
  END IF;
END $$;

COMMIT;
