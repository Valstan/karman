-- 0036_accounts_usage_event_log — журнал активаций становится ЖУРНАЛОМ СОБЫТИЙ.
--
-- РУКОПИСНАЯ миграция (KARMAN не гоняет drizzle-kit generate). Применяется на проде
-- через psql ДО деплоя: migration-guard в deploy-prod.yml блокирует авто-деплой для
-- коммита с миграцией (лечение — журнал schema_migrations, см. тех-долг).
--
-- ЗАЧЕМ. Строка журнала была ОДНА на аккаунт в сутки (UNIQUE (account_id, used_on)),
-- поэтому повторная выдача того же аккаунта в те же московские сутки ПЕРЕЗАПИСЫВАЛА
-- прежнюю строку — и статистика расхода теряла половину выдач. Живые числа:
-- 19.11 — аудит 118 выдач / 97 000 очков, журнал — 66 строк / 46 800 очков;
-- 17.11 — 163 выдачи / 66 400 очков против 111 строк / 47 400 очков.
--
-- Теперь журнал — СОБЫТИЯ: одна строка на одну выдачу («кто, когда и за сколько очков
-- взял этот аккаунт»). Продолжение работы в рамках одной сессии обновляет СВОЮ строку;
-- новая выдача (сессия закрыта, аккаунт снова свободен) заводит НОВУЮ.
--
-- ЧТО НЕ МЕНЯЕТСЯ. Правило одной правды остаётся в силе: пока сессия аккаунта
-- открыта, второй потребитель его не получает (окно простоя + `onlyIfFree` на уровне
-- БД). Меняется только УЧЁТ: теперь видно каждую выдачу, а не последнюю за сутки.
--
-- ДАННЫЕ НЕ ТЕряются: миграция меняет только индекс, строки остаются как есть.
--
-- ИНВАРИАНТЫ:
--   - индекс (account_id, used_on) остаётся, но НЕ уникальный: по нему ищем строки
--     сессии и считаем чек-ины аккаунта;
--   - отметка владельца и отметка потребителя — теперь РАЗНЫЕ строки, а не одна с
--     переписанной меткой: у каждой выдачи своя метка и свой проект;
--   - ограничение activation_index BETWEEN 1 AND 7 (миграция 0029) остаётся: клетка
--     вендора по-прежнему 1..7.

BEGIN;

DROP INDEX IF EXISTS accounts_usage_account_day_uq;

CREATE INDEX IF NOT EXISTS accounts_usage_account_day_idx
  ON accounts_usage (account_id, used_on);

COMMIT;
