-- 0023_grant_policy — политики приёма выдач (S2 дорожной карты доступов, D-119).
--
-- РУКОПИСНАЯ миграция (KARMAN не гоняет drizzle-kit generate). Применяется
-- на проде через psql ДО деплоя (migration-guard в deploy-prod.yml блокирует
-- авто-деплой → деплой через workflow_dispatch).
--
-- Политика приёма — allowlist, которую комната-получатель объявляет
-- ОДИН раз: «принимаю ключ KEY от комнаты-источника как ALIAS». Дальше
-- предложение выдачи токеном источника принимается автоматически (auto-accept)
-- с аудит-строкой, где указана политика. Согласие выражено один раз
-- политикой (#272: согласие — фича), отзыв политики — одной строкой и
-- вступает сразу: будущие предложения ждут ручного accept, уже принятые
-- выдачи остаются (согласие на них уже дано в момент приёма).
--
-- Инварианты:
--   - одна ЖИВАЯ политика на (target, source, key): частичный уникальный
--     индекс; повторное объявление — 409, а не молчаливый дубль;
--   - alias_key NOT NULL: политика фиксирует имя, под которым значение
--     приезжает в комнату (по умолчанию = имя ключа источника);
--   - каскад на обеих сторонах: удаление комнаты снимает и её политики.

BEGIN;

CREATE TABLE IF NOT EXISTS secrets_grant_policy (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_project_id  bigint   NOT NULL REFERENCES secrets_project (id) ON DELETE CASCADE,
  source_project_id  bigint   NOT NULL REFERENCES secrets_project (id) ON DELETE CASCADE,
  source_key         varchar(200) NOT NULL,
  alias_key          varchar(200) NOT NULL,
  note               text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  revoked_at         timestamptz
);

-- Одна живая политика на тройку (комната-получатель, комната-источник, ключ).
CREATE UNIQUE INDEX IF NOT EXISTS secrets_grant_policy_live_uq
  ON secrets_grant_policy (target_project_id, source_project_id, source_key)
  WHERE revoked_at IS NULL;

CREATE INDEX IF NOT EXISTS secrets_grant_policy_target_idx
  ON secrets_grant_policy (target_project_id, revoked_at);

COMMIT;
