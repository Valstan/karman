-- 0024_accounts — мультиаккаунт владельца (задача 2026-11-03).
--
-- РУКОПИСНАЯ миграция (KARMAN не гоняет drizzle-kit generate). Применяется
-- на проде через psql ДО деплоя (migration-guard в deploy-prod.yml блокирует
-- авто-деплой → деплой через workflow_dispatch).
--
-- Что это: список аккаунтов внешних сервисов, которыми владелец переключается,
-- пока программирует. У каждого — почта, название и зашифрованный пароль.
-- Аккаунт, который сегодня использован, «тушится» до завтра (used_on —
-- московская дата активации); на следующие сутки он снова свободен. Никакой
-- ночной задачи: доступность считается при чтении.
--
-- Проекты — справочник названий («Матрица РМЗ», «Сабантуй», «Казанская»):
-- на какой проект ушли токены этого аккаунта. Журнал активаций
-- (accounts_usage) копит расход по проектам — по нему считается статистика
-- «на какой проект больше токенов».
--
-- Инварианты:
--   - пароль лежит ТОЛЬКО шифротекстом (AES-256-GCM, AAD привязан к id
--     аккаунта) — как и значения секретов в vault;
--   - почта — идентификатор входа (как логин), поэтому в открытом виде;
--   - один аккаунт на почту: UNIQUE (user_id, email);
--   - каскад: удаление пользователя или проекта убирает свои записи;
--   - used_project_id — «на чём последний раз активировали», SET NULL при
--     удалении проекта (аккаунт остаётся, история — в accounts_usage).

BEGIN;

CREATE TABLE IF NOT EXISTS accounts_project (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer      NOT NULL REFERENCES auth_user (id) ON DELETE CASCADE,
  name       varchar(200) NOT NULL,
  created_at timestamptz  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS accounts_project_user_name_uq
  ON accounts_project (user_id, name);

CREATE TABLE IF NOT EXISTS accounts_account (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          integer      NOT NULL REFERENCES auth_user (id) ON DELETE CASCADE,
  title            varchar(200) NOT NULL DEFAULT '',
  email            varchar(320) NOT NULL,
  -- Пароль: AES-256-GCM (ciphertext/iv/auth_tag), AAD = accounts:account:<id>:password.
  password_ct      text NOT NULL,
  password_iv      text NOT NULL,
  password_tag     text NOT NULL,
  -- Москва-дата последней активации (YYYY-MM-DD) и момент активации (UTC).
  used_on          date,
  used_at          timestamptz,
  used_project_id  bigint REFERENCES accounts_project (id) ON DELETE SET NULL,
  last_tokens      bigint NOT NULL DEFAULT 0,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS accounts_account_user_email_uq
  ON accounts_account (user_id, email);

CREATE INDEX IF NOT EXISTS accounts_account_user_idx
  ON accounts_account (user_id);

-- Журнал активаций: кто, на каком проекте, когда и сколько токенов ушло.
CREATE TABLE IF NOT EXISTS accounts_usage (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer      NOT NULL REFERENCES auth_user (id) ON DELETE CASCADE,
  account_id bigint       NOT NULL REFERENCES accounts_account (id) ON DELETE CASCADE,
  project_id bigint REFERENCES accounts_project (id) ON DELETE SET NULL,
  used_on    date NOT NULL,
  tokens     bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS accounts_usage_user_project_idx
  ON accounts_usage (user_id, project_id);

-- Одна активация аккаунта на сутки: пока окно 24 часа не истекло, повторная
-- активация — продолжение той же сессии, а не новая (иначе статистика по
-- проектам удваивалась бы). С 05.11 гасит аккаунт только явная кнопка
-- «Активировать»; ограничение осталось тем же.
CREATE UNIQUE INDEX IF NOT EXISTS accounts_usage_account_day_uq
  ON accounts_usage (account_id, used_on);

COMMIT;
