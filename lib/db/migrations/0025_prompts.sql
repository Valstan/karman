-- 0025_prompts — библиотека промтов по проектам (заказ владельца 2026-11-06).
--
-- РУКОПИСНАЯ миграция (KARMAN не гоняет drizzle-kit generate). Применяется
-- на проде через psql ДО деплоя (migration-guard в deploy-prod.yml блокирует
-- авто-деплой → деплой через workflow_dispatch).
--
-- Что это: промты, которые владелец надиктовывает в чат, а Мозг раскладывает
-- по проектам. Источник правды — эта таблица, а не репозиторий Мозга: у промта
-- есть кнопки «Копировать» и «В архив», а у КАРМАНА на репозиторий Мозга токен
-- ТОЛЬКО на чтение (BRAIN_MAP_GITHUB_TOKEN, Contents: read) — писать туда из
-- приложения нечем.
--
-- Разделы по проектам — колонка project: название проекта из реестра Мозга
-- (projects/INDEX.md). Строки без проекта не бывает: без раздела список
-- превращается в свалку, а разложить его потом нечем.
--
-- Архив — НЕ удаление: archived_at проставляется, строка остаётся (может
-- пригодиться для истории и для обучения — так просил владелец). Чистится
-- вручную из интерфейса: «очистить архив» и «удалить из архива» — тот самый
-- escape hatch, о котором шла речь («мало ли раздастся до больших размеров»).
--
-- Инварианты:
--   - body — нормализованный текст промта: ровно то, что уходит в буфер
--     обмена и дальше в нейронку;
--   - title — короткое имя для списка; если не задан, берётся первая строка
--     промта (деривация детерминированная, см. lib/prompts/normalize.ts);
--   - source — 'manual' (человек в интерфейсе) или 'brain' (Мозг по команде
--     владельца): видно, откуда взялась строка;
--   - created_at — когда промт создан (в списке видно, «когда это происходило»);
--   - таблица БЕЗ user_id: библиотека одна на приложение — как карта проектов,
--     вкладки которой тоже видны всем вошедшим. Право записи — только у
--     владельца (суперпользователя) и у машинного канала Мозга (Bearer).

BEGIN;

CREATE TABLE IF NOT EXISTS prompt (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project     varchar(64)  NOT NULL,
  title       varchar(200) NOT NULL DEFAULT '',
  body        text         NOT NULL,
  source      varchar(16)  NOT NULL DEFAULT 'manual',
  created_at  timestamptz  NOT NULL DEFAULT now(),
  archived_at timestamptz
);

-- Выборка «живых» промтов по проекту и чтение архива — два основных запроса.
CREATE INDEX IF NOT EXISTS prompt_project_created_idx
  ON prompt (project, created_at DESC);

CREATE INDEX IF NOT EXISTS prompt_archived_idx
  ON prompt (archived_at);

COMMIT;
