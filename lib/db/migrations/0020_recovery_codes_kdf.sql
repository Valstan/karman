-- 0020_recovery_codes_kdf - соль для recovery-кодов (аудит #057, находка S2).
--
-- Дефект был не «коды слабые вообще», а в двух конкретных вещах: ~49,5 бита энтропии на
-- код (алфавит из 31 символа, 10 байт) и НЕСОЛЁНЫЙ SHA-256 без раундов в таблице. Оба
-- бьют по ОФЛАЙН-перебору из дампа БД, а не по онлайн-подбору (тот душит login-guard).
--
-- Важная асимметрия, которую стоит помнить: секрет TOTP в дампе зашифрован
-- мастер-ключом vault'а, поэтому тот же дамп его НЕ раскрывает. Recovery-коды были
-- единственным элементом 2FA, который дамп отдавал наружу целиком. Соль и KDF закрывают
-- именно этот сценарий, а не что-то новое.
--
-- Формат кодов меняется отдельной правкой кода (100 бит вместо 49,5); миграция добавляет
-- только соль. Строки со старыми кодами остаются рабочими: у них code_salt IS NULL, и
-- проверка узнаёт их по отсутствию соли. Владелец перевыдаёт коды кнопкой в настройках
-- (решение владельца 2026-10-03 — «выдавать заново»), после чего все строки получают соль.

ALTER TABLE auth_recovery_code ADD COLUMN code_salt varchar(64);