-- 0028_prompt_project — реестр разделов библиотеки промтов (заказ владельца 2026-11-06).
--
-- «НАЗВАНИЯ ПРОЕКТАМ создай сам по канону… создай там заранее все разделы всех
-- проектов, которые есть у нас в экосистеме на данный момент.»
--
-- До этого разделами считались РАЗНЫЕ значения project среди промтов: пустой
-- раздел невозможен, а значит и заранее создать раздел нельзя. Теперь есть
-- отдельный реестр: имя раздела живёт здесь, промты ссылаются на него по имени.
-- Так можно завести все разделы экосистемы заранее — и пустые тоже видны.
--
-- Реестр ЛИЧНЫЙ (user_id): у каждого аккаунта своя раскладка разделов, как и
-- сами промты (ownership, без исключения для суперпользователя).
--
-- Бэкфилл: разделы, которые уже набрались из промтов, становятся строками
-- реестра. Канонические имена разделов приезжают сверху (машинный канал Мозга),
-- поэтому здесь только фактические — переименование делается отдельно и явно.
--
-- РУКОПИСНАЯ миграция: psql на проде ДО деплоя (migration-guard → workflow_dispatch).

BEGIN;

CREATE TABLE IF NOT EXISTS prompt_project (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer      NOT NULL REFERENCES auth_user(id) ON DELETE CASCADE,
  name       varchar(64)  NOT NULL,
  created_at timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT prompt_project_user_name_key UNIQUE (user_id, name)
);

CREATE INDEX IF NOT EXISTS prompt_project_user_idx
  ON prompt_project (user_id, name);

-- Бэкфилл: уже накопленные разделы — в реестр.
INSERT INTO prompt_project (user_id, name)
SELECT DISTINCT user_id, project FROM prompt
ON CONFLICT (user_id, name) DO NOTHING;

COMMIT;
