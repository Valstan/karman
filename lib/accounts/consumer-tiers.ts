/**
 * Роли комнат-потребителей и формат статистики тысячных (заказ владельца 19.11).
 *
 * Модуль ЧИСТЫЙ: его читает и клиентский компонент страницы, поэтому здесь не должно
 * быть ничего, что тянет Node-модули (иначе сборка клиентского бандла падает на `pg`).
 * Сама выборка — в `lib/services/minimax-consumer-tiers.ts`.
 */

/**
 * Роли комнат-потребителей: slug комнаты → подпись роли.
 *
 * Класс очков выбираем **мы**, по комнате-потребителю (`TIER_PREFERENCE` в
 * `lib/services/minimax.ts`): комната `brain` — панели программирования владельца —
 * получает тысячные первыми, комната `setka` — продсервер Сарафана (фильтрация постов
 * ВК) — сначала четырёхсотковые. Имя проекта для этого НЕ годится: у владельца
 * «САРАФАН» (кириллица) и у комнаты «SARAFAN» (латиница) — разница в одном символе,
 * а ловушка, а не различие (см. комментарий в `lib/db/schema.ts`).
 */
export const CONSUMER_ROLES: Record<string, string> = {
  /** Панели программирования владельца (десктопы областей). */
  brain: 'программирование',
  /** Продсервер Сарафана: комната обрабатывает посты ВК. */
  setka: 'продсервер Сарафана',
};

/** Роль для комнат, которых нет в `CONSUMER_ROLES`. */
export const OTHER_ROLE = 'прочие комнаты';

/** Строка «сутки × роль». */
export type ConsumerTierDay = {
  /** Москва-дата выдачи ('YYYY-MM-DD'). */
  usedOn: string;
  /** Роль потребителя (см. `CONSUMER_ROLES`). */
  role: string;
  /** Slug комнаты, которая брала аккаунты. */
  room: string;
  /** Сколько тысячных (points_1000) отдано в эти сутки. */
  thousands: number;
  /** Сколько четырёхсотковых (points_400) отдано. */
  fours: number;
  /** Очков отдано всего. */
  points: number;
  /** Всего выдач (включая классы «0 очков» и без класса). */
  issues: number;
};

/** Свод по ролям. */
export type ConsumerTierRole = {
  role: string;
  thousands: number;
  fours: number;
  points: number;
  issues: number;
};

/** Ответ сервиса: свод по ролям и по суткам. */
export type ConsumerTiers = {
  /** Окно в сутках, за которое собраны данные. */
  days: number;
  /** Свод по ролям (программирование, продсервер Сарафана, прочие). */
  byRole: ConsumerTierRole[];
  /** По суткам — свежие сверху. */
  byDay: ConsumerTierDay[];
};
