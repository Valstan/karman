/**
 * Тексты блока «Пул и бонусы» — чистой функцией, чтобы его можно было проверить
 * тестом (заказ владельца 21.11).
 *
 * ## Зачем функция, а не разметка
 *
 * Владелец пожаловался: «все равно не понимаю эту статистику, какая-то каша
 * малаша, одна строка про одно говорит, вторая ей противоречит… Надо доработать
 * переработать статистику, ничего не понимаю где тут правда». Значит, важно не
 * только КАКИЕ числа считаются, но и КАК они подписаны. Подписи — это текст, и
 * текст должен быть под гейтом: иначе следующий правдоподобный «свод по запасу»
 * снова встанет рядом с блоком бонусов и снова начнёт с ним спорить.
 *
 * ## Правила блока (одна строка — одно утверждение)
 *
 * 1. **Окно суток названо явно** — 05:00 → 05:00 МСК, забор в 05:00.
 * 2. **Пул** — сколько свободно, сколько реально готово к выдаче (столько же,
 *    сколько показывает кнопка), сколько всего в парке.
 * 3. **Забор** — сколько клеток и очков забрали мы за сутки (из них тысячных),
 *    сколько аккаунтов обошли.
 * 4. **Отдано** — сколько аккаунтов и очков ушло потребителям.
 * 5. **Осталось сегодня** — свежие клетки текущих суток (их ещё можно отдать),
 *    отдельно — сколько из них тысячных (их надо отдавать первыми).
 * 6. **С прошлых суток** — старый забор, который никто не забрал: это НЕ
 *    «осталось сегодня» (так его и читал владелец в числе 173 200).
 * 7. **Мимо нас** — клетку забрал потребитель ДО нашего забора: очки ушли ему.
 * 8. **Нитки бонусов** — текущая клетка вендора по аккаунтам и проверка, что
 *    нить не рвалась (это ответ на вопрос «продлевается ли нитка бонусов»).
 * 9. **Темп отдачи** — сколько очков в сутки уходит потребителям, по фактическим
 *    суткам с выдачами. Недельного прогноза («хватит / не хватит на неделю»)
 *    нет: по заказу владельца очки не копятся на неделю.
 */

/** Сводка по бонусам за операционные сутки (окно 05:00 → 05:00 МСК). */
export type BonusStatsView = {
  /** Подпись окна: '21.11 → 22.11'. */
  label: string;
  /** Сколько клеток забрали мы за сутки. */
  collected: number;
  /** Сколько очков забрали мы за сутки. */
  collectedPoints: number;
  /** Сколько клеток забрал потребитель (мимо нас). */
  consumerTaken: number;
  /** Сколько очков забрал потребитель. */
  consumerTakenPoints: number;
  /** Сколько разных аккаунтов клетку забрали за сутки (наши и чужие). */
  claimedAccounts: number;
  /** Сколько аккаунтов отдали за сутки. */
  handed: number;
  /** Сколько очков отдали за сутки. */
  handedPoints: number;
  /** Остаток на аккаунтах: наши клетки, которые ещё не отдали (очки). */
  stockPoints: number;
  /** Сколько РАЗНЫХ аккаунтов держат этот остаток. */
  stockAccounts: number;
  /** Сколько тысячных клеток забрали за сутки — по леджеру (правда). */
  thousands: number;
  /** Остаток текущих суток: наши клетки, забранные в окне и не отданные. */
  freshPoints: number;
  /** Сколько таких клеток. */
  freshCells: number;
  /** Сколько разных аккаунтов их держат. */
  freshAccounts: number;
  /** Сколько тысячных из них ждут в пуле (их отдаём первыми). */
  freshThousands: number;
  /** Сколько очков в этих тысячных. */
  freshThousandsPoints: number;
  /** Остаток прошлых суток: наши клетки, забранные до окна и не отданные. */
  olderPoints: number;
  /** Сколько таких клеток. */
  olderCells: number;
  /** Текущая клетка вендора по аккаунтам: клетка → сколько аккаунтов. */
  cells: { cell: number; points: number; accounts: number }[];
  /** Сколько серий сгорело (0 — нить цела). */
  seriesBroken: number;
  /** Темп: очков в сутки по срезу последних полных операционных суток. */
  pointsPerDay: number | null;
  /** Сколько суток с выдачами попало в срез темпа. */
  sliceDays: number;
  /** Начало среза темпа (московская дата начала суток) — первый день с данными. */
  sliceFrom: string;
  /** Конец среза темпа (московская дата начала суток) — последний день с данными. */
  sliceTo: string;
};

/** Одна строка блока: подпись и значение. */
export type PoolLine = {
  /** Подпись строки (левая колонка). */
  label: string;
  /** Значение строки (правая колонка). */
  value: string;
};

/** Число с неразрывными пробелами — так владелец привык читать очки. */
function num(value: number): string {
  return value.toLocaleString('ru-RU');
}

/**
 * Русское окончание по числу: 1 клетка / 2 клетки / 5 клеток.
 *
 * Без этого в блоке появляется «1 клеток» — а владелец читает каждую строку
 * внимательно.
 */
export function plural(count: number, one: string, few: string, many: string): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return few;
  return many;
}

/** «5 клеток» — число с правильным окончанием. */
function counted(count: number, one: string, few: string, many: string): string {
  return `${num(count)} ${plural(count, one, few, many)}`;
}

/**
 * Строки блока «Пул и бонусы».
 *
 * `pool` — то, что знает сам список аккаунтов: сколько в парке, сколько не заняты
 * (окно простоя истекло — их и считает кнопка «Выдать аккаунт») и сколько из них с
 * целыми очками (по леджеру и панели).
 *
 * **Почему три числа, а не два.** «Не заняты» и «с целыми очками» — разные вещи:
 * аккаунт может быть не заняты, а его очки уже сожжены потребителем (клетку забрали
 * до нас). Подписи «свободны» и «готовы к выдаче» путались между собой: второе
 * читалось как подмножество первого, хотя наоборот (кнопка считает всех не занятых).
 */
export function poolBonusLines(
  stats: BonusStatsView,
  pool: {
    /** Сколько аккаунтов с целыми очками (по леджеру и панели). */
    free: number;
    /** Сколько не заняты (окно простоя истекло) — столько же, сколько показывает кнопка выдачи. */
    ready: number;
    /** Сколько всего в парке. */
    park: number;
  },
): PoolLine[] {
  const lines: PoolLine[] = [];

  lines.push({
    label: 'Сутки',
    value: `${stats.label} · окно 05:00 → 05:00 МСК (забор бонусов в 05:00)`,
  });

  lines.push({
    label: 'Пул',
    value:
      `${pool.park} в парке · ${pool.ready} не заняты · ${pool.free} с целыми очками`,
  });

  lines.push({
    label: 'Забор',
    value:
      `${counted(stats.collected, 'клетка', 'клетки', 'клеток')} на ` +
      `${num(stats.collectedPoints)} очков` +
      (stats.thousands > 0 ? ` (из них ${stats.thousands} — тысячные)` : '') +
      ` · обошли ${counted(stats.claimedAccounts, 'аккаунт', 'аккаунта', 'аккаунтов')}`,
  });

  lines.push({
    label: 'Отдано',
    value: `${counted(stats.handed, 'аккаунт', 'аккаунта', 'аккаунтов')} на ${num(stats.handedPoints)} очков`,
  });

  lines.push({
    label: 'Осталось сегодня',
    value:
      `${num(stats.freshPoints)} очков на ${counted(stats.freshAccounts, 'аккаунте', 'аккаунтах', 'аккаунтах')}` +
      (stats.freshThousands > 0
        ? ` (из них ${num(stats.freshThousandsPoints)} — тысячные, ${counted(stats.freshThousands, 'аккаунт', 'аккаунта', 'аккаунтов')})`
        : ''),
  });

  if (stats.olderCells > 0) {
    lines.push({
      label: 'С прошлых суток',
      value:
        `${num(stats.olderPoints)} очков в ${counted(stats.olderCells, 'клетке', 'клетках', 'клетках')} — ` +
        'номинал, не отдано',
    });
  }

  if (stats.consumerTaken > 0) {
    lines.push({
      label: 'Мимо нас',
      value:
        `${counted(stats.consumerTaken, 'клетка', 'клетки', 'клеток')} на ` +
        `${num(stats.consumerTakenPoints)} очков — забрал потребитель до нашего забора`,
    });
  }

  const thousands = stats.cells.filter((cell) => cell.points >= 1000);
  const plain = stats.cells.filter((cell) => cell.points < 1000);
  const sum = (list: { accounts: number }[]) =>
    list.reduce((total, cell) => total + cell.accounts, 0);
  const cellList = (list: { cell: number }[]) => list.map((cell) => cell.cell).join(', ');
  lines.push({
    label: 'Нитки бонусов',
    value:
      `${counted(sum(thousands), 'аккаунт', 'аккаунта', 'аккаунтов')} на тысячной` +
      (cellList(thousands) ? ` (клетки ${cellList(thousands)})` : '') +
      ` · ${counted(sum(plain), 'аккаунт', 'аккаунта', 'аккаунтов')} на обычной` +
      (cellList(plain) ? ` (клетки ${cellList(plain)})` : '') +
      ' · ' +
      (stats.seriesBroken === 0 ? 'ни одна серия не сгорела' : `сгорело серий: ${stats.seriesBroken}`),
  });

  lines.push({
    label: 'Темп отдачи',
    value:
      stats.pointsPerDay === null
        ? '—'
        : `${num(Math.round(stats.pointsPerDay))} очк./сутки ` +
          `(${stats.sliceFrom}—${stats.sliceTo}, ${stats.sliceDays} суток с выдачами)`,
  });

  return lines;
}
