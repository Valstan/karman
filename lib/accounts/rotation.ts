/**
 * Мультиаккаунт: правило простоя и порядок списка.
 *
 * Задача владельца (2026-11-03): аккаунты внешних сервисов, которыми он
 * переключается, пока программирует. Правило уточнено 04.11: активация
 * даёт аккаунту СВОИ часы простоя — от момента активации, а не до общей
 * полуночи по календарю. Активировали в 23:50 — аккаунт свободен в 05:50.
 *
 * С 07.11 окно простоя — **10 ЧАСОВ** (07.11 влалелец просил 6 часов, 08.11
 * растянул до 10: «ну, давай до 10 часов, что ли, его растянем, потому что
 * иногда… некоторые токены приходят, уже активированы… то есть бонус ему не
 * дается»), а **с 11.11 — 5 ЧАСОВ**: столько же длится окно расхода у MiniMax,
 * и «занятость» у нас перестала быть выдумкой (решение владельца 11.11). Что
 * это меняет:
 *
 * - очки по-прежнему даёт ЕЖЕДНЕВНЫЙ чек-ин (раз в сутки на аккаунт), и
 *   ограничителем недели теперь стал не суточный инвариант, а **недельная
 *   квота в 7 активаций** (см. `lib/accounts/weekly.ts`): неделя у аккаунта
 *   своя — 7 дней от его ПЕРВОГО использования (так устроено окно MiniMax);
 * - журнал по-прежнему хранит ОДНУ строку на аккаунт на московские сутки:
 *   повторная активация того же дня обновляет строку дня, а не плодит вторую.
 *   Поэтому ни одна миграция схемы для перехода 24 ч → 10 ч не понадобилась —
 *   менялось правило простоя, а не структура журнала;
 * - аккаунт, у которого неделя исчерпана (7 из 7), **не предлагается** для
 *   активации: он уходит вниз списка вместе с занятыми.
 *
 * Сессия активации: окно открывает явная кнопка «Активировать» (заказ владельца
 * 05.11: копирование почты или пароля аккаунт НЕ гасит). Пока сессия открыта,
 * повторная активация того же аккаунта её ПРОДОЛЖАЕТ: окно не сдвигается, в
 * журнале одна строка, поэтому статистика не удваивается.
 *
 * ПОЧЕМУ РАНЬШЕ БЫЛО РОВНО 24 ЧАСА (проверено 06.11 по документации MiniMax):
 * очки даёт ежедневный чек-ин (400 очков, в 4-й и 7-й дни — 1000), то есть
 * один раз в сутки на аккаунт. Окно 18 часов (пробовали 06.11) эту гарантию
 * ломало: вторая запись в журнале считала бы очки, которых нет. С 07.11
 * ограничение перенесено на недельную квоту, и окно можно сократить — подробности
 * в docs/minimax.md.
 *
 * Порядок экрана (заказ владельца 04.11): наверху ОДИН аккаунт — тот, что
 * дольше всех не активировался (никогда не использованный — самый первый);
 * после его активации наверх встаёт следующий. Ниже — активированные, и чем
 * позже активирован, тем выше (свежий сверху).
 *
 * Никакой ночной задачи: доступность считается при чтении, поэтому аккаунт
 * сам становится свободным по истечении своего окна.
 *
 * Модуль чистый (без server-only и без БД) — юнит-тестируется.
 */

import { utcToMoscowLocal } from '@/lib/reminders/time';

/**
 * Сколько часов живёт активация аккаунта (окно простоя).
 *
 * **5 часов** — решение владельца 11.11. Ровно столько же длится окно расхода
 * у MiniMax (5-часовое, «all except image and video models»), поэтому «занят»
 * у нас теперь значит ровно то же, что у них: аккаунт снова готов к работе
 * через пять часов после первого использования. Наша «занятость» перестала быть
 * выдумкой — раньше окно было 10 часов (заказ 08.11) и держалось на страхе, что
 * вторая активация в тот же день слот уйдёт вхолостую.
 *
 * Очки при этом не теряются: чек-ин в сутки один, поэтому повторная активация
 * в тот же день всё равно даёт 0 очков — но аккаунт переоткрывается для работы,
 * у него восстановилась 5-часовая квота расхода (заказ владельца 11.11:
 * «в один день несколько раз очки активировать — это не страшно»).
 *
 * Ограничителем недели остаётся не это окно, а недельная квота в 7 активаций
 * (см. `lib/accounts/weekly.ts`): неделя у аккаунта своя — 7 дней от первого
 * использования (так устроено окно MiniMax).
 */
export const ACTIVATION_WINDOW_HOURS = 5;

/** Окно простоя в миллисекундах. */
export const ACTIVATION_WINDOW_MS = ACTIVATION_WINDOW_HOURS * 3_600_000;

/**
 * Сколько активированных аккаунтов показывать по умолчанию (заказ владельца
 * 04.11: «последних 10 последних активированных, пусть будет так»; 05.11:
 * «оставим активированных аккаунтов не 10, а 5»). Остальные открываются кнопкой
 * «показать все аккаунты».
 */
export const ACTIVATED_PREVIEW_LIMIT = 5;

/**
 * Очки за активацию по умолчанию — больше не константа, а функция от номера
 * активации в неделе (заказ владельца 07.11: 400 в обычный день, 1000 в 4-й и
 * 7-й; номер считает `lib/accounts/weekly.ts`).
 *
 * Прежняя константа `DEFAULT_ACTIVATION_TOKENS = 400` (заказ 05.11: «обычно 400
 * дается, но иногда 1000 — тогда я стеру 400 и напишу 1000») удалена 07.11:
 * фиксированное 400 перекрывало 1000 в 4-й и 7-й активациях. Теперь значение
 * подставляется по номеру — `pointsForIndex` в `lib/accounts/weekly.ts`.
 *
 * Это очки ежедневного чекина MiniMax, а не токены модели: в интерфейсе поле
 * так и называется — «Очки». Имена в БД и в типах остались историческими
 * (`tokens`) — менять их значило бы тащить миграцию ради слов.
 */

/** Московская дата 'YYYY-MM-DD' для момента времени. */
export function moscowToday(now: Date = new Date()): string {
  return utcToMoscowLocal(now).slice(0, 10);
}

/**
 * Когда аккаунт снова станет свободен (ISO) или null — если он ещё не
 * активировался ни разу.
 */
export function availableAt(usedAt: string | null): string | null {
  if (!usedAt) return null;
  return new Date(new Date(usedAt).getTime() + ACTIVATION_WINDOW_MS).toISOString();
}

/**
 * Израсходован ли аккаунт: не истекли ли часы окна с момента активации.
 *
 * Сравнение с моментом активации, а не с датой: у каждого аккаунта своё
 * окно (правило владельца 04.11).
 */
export function isSpent(account: { usedAt: string | null }, now: Date = new Date()): boolean {
  if (!account.usedAt) return false;
  return new Date(account.usedAt).getTime() + ACTIVATION_WINDOW_MS > now.getTime();
}

/**
 * Недоступен ли аккаунт для активации — по двум причинам сразу:
 *
 * 1. окно простоя не истекло (аккаунт занят);
 * 2. недельная квота исчерпана (7 активаций из 7 — аккаунт до следующего
 *    цикла не предлагается, заказ владельца 07.11).
 *
 * Исчерпанный аккаунт уходит вниз списка вместе с занятыми — наверх он встать
 * не должен.
 */
export function isUnavailable(
  account: { usedAt: string | null; weekExhausted?: boolean },
  now: Date = new Date(),
): boolean {
  return isSpent(account, now) || account.weekExhausted === true;
}

/**
 * «Скоро освободятся» — окно в полчаса (заказ владельца 06.11: «сколько
 * аккаунтов скоро освободятся, в ближайшие полчата»).
 */
export const SOON_RELEASE_WINDOW_MS = 30 * 60_000;

/**
 * Короткая сводка по запасу аккаунтов: сколько свободно сейчас и сколько
 * освободится в ближайшие полчаса (заказ владельца 06.11).
 *
 * Считается по окнам, а не по датам: у каждого аккаунта своё время
 * освобождения, поэтому «скоро» — это про остаток окна, а не про календарь.
 *
 * `free` — все живые аккаунты, которыми можно взять прямо сейчас, включая
 * предложенный в верхнем слоте (тот самый тоже свободен). Аккаунты с
 * исчерпанной неделей (7 из 7) в `free` НЕ входят: ими нельзя взять — неделя
 * кончилась (заказ владельца 07.11).
 */
export function accountPoolSummary(
  accounts: AccountRotationRow[],
  now: Date = new Date(),
): { free: number; soon: number } {
  let free = 0;
  let soon = 0;
  for (const account of accounts) {
    if (account.weekExhausted) continue;
    if (!isSpent(account, now)) {
      free += 1;
      continue;
    }
    const releasesAt = new Date(account.usedAt!).getTime() + ACTIVATION_WINDOW_MS;
    if (releasesAt - now.getTime() <= SOON_RELEASE_WINDOW_MS) soon += 1;
  }
  return { free, soon };
}

/** Состояние аккаунта в том виде, в котором его видит список. */
export type AccountRotationRow = {
  id: number;
  /** Название (своя метка владельца: «Матрица РМЗ — 1»). */
  title: string;
  email: string;
  /**
   * Москва-дата начала сессии активации ('YYYY-MM-DD') или null — не
   * активировался. В сессии не меняется: по ней ищется строка журнала.
   */
  usedOn: string | null;
  /**
   * Момент начала сессии активации (ISO UTC) или null. Окно простоя считается
   * от него, поэтому при продолжении сессии он не меняется.
   */
  usedAt: string | null;
  /** Проект последней активации (id / имя) — «на что ушли эти очки». */
  projectId: number | null;
  projectName: string | null;
  /** Очки за последнюю активацию. */
  lastTokens: number;
  /** Сколько активаций уже сделано в текущем недельном цикле аккаунта. */
  weekUsed: number;
  /** Исчерпана ли неделя аккаунта (7 из 7) — такой аккаунт не предлагается. */
  weekExhausted: boolean;
  /**
   * Был ли сегодня (по Москве) чек-ин у аккаунта.
   *
   * Чек-ин в сутки один, поэтому у такого аккаунта сегодняшнего бонуса уже
   * нет: активировать его снова — значит не получить ничего (заказ владельца
   * 08.11: «некоторые токены приходят, уже активированы… то есть бонус ему не
   * дается»). Поэтому в верхний слот такие аккаунты не попадают.
   */
  weekCheckedInToday: boolean;
  /**
   * Очки, которые даст следующая активация (0 — чек-ин за сегодня уже был).
   *
   * По ним аккаунты и сравниваются между собой: 1000 (клетка 4 или 7) важнее
   * 400, а 400 — уже вхолостую.
   */
  weekPointsNext: number;
  /**
   * Сколько активаций подряд (включая ближайшую) до следующей бонусной клетки:
   * 1 — бонус сегодня, 4 — бонус через три дня.
   */
  weekDaysToBonus: number;
  /** Длина текущей серии дней подряд (0 — серия сгорела). */
  weekStreak: number;
};

/**
 * Порядок списка: сначала доступные, потом израсходованные.
 *
 * Внутри доступной группы порядок — **по деньгам** (заказ владельца 11.11:
 * «предлагай в первую очередь те, у которых больше всего активаций за цикл»,
 * «новые аккаунты в оборот брать только по мере надобности»):
 *
 * 1. **очки следующей активации** — 1000 (клетка 4 или 7) вперёд, 400 дальше,
 *    0 (чек-ин за сегодня уже был) — в самый низ: такой слот уйдёт вхолостую;
 * 2. **расстояние до ближайшей бонусной клетки** — меньше лучше: аккаунт, которому
 *    до 1000 остался один день, пропускать нельзя, бонус сгорит до следующей
 *    недели, а у свежего (клетка 1) до бонуса четыре дня;
 * 3. **длина серии** — больше лучше: больше накопленного;
 * 4. **давность использования** — как было раньше: никогда не использованные
 *    первыми, затем те, что использовались раньше всего.
 *
 * Проверено пересчётом боевой недели 11.11 (85 аккаунтов, тот же дневной бюджет
 * активаций): было 152 600 очков, стало 246 200 (+61 %).
 *
 * Внутри израсходованных — СВЕЖИЙ СВЕРХУ (04.11: «чем позже активирован, тем
 * выше он находится»): последний активированный аккаунт должен быть сразу под
 * верхним слотом, а не улетать вниз списка.
 */
export function sortAccounts<T extends AccountRotationRow>(
  accounts: T[],
  now: Date = new Date(),
): T[] {
  return [...accounts].sort((a, b) => {
    // Недоступны (заняты окном ИЛИ исчерпана неделя) — вниз списка.
    const aDown = isUnavailable(a, now);
    const bDown = isUnavailable(b, now);
    // Сначала доступные: недоступные уходят вниз.
    if (aDown !== bDown) return aDown ? 1 : -1;
    if (aDown) {
      // Среди активированных свежий сверху.
      if (a.usedAt !== b.usedAt) return a.usedAt! < b.usedAt! ? 1 : -1;
      return a.id - b.id;
    }
    // Среди доступных — сначала те, у кого сегодня ещё можно получить очки.
    // У отмеченного сегодня очков сегодня не будет (чек-ин в сутки один) —
    // такой аккаунт в верхний слот не встаёт.
    if (a.weekCheckedInToday !== b.weekCheckedInToday) {
      return a.weekCheckedInToday ? 1 : -1;
    }
    // 1) Очки следующей активации: 1000 (клетка 4 или 7) вперёд.
    if (a.weekPointsNext !== b.weekPointsNext) return b.weekPointsNext - a.weekPointsNext;
    // 2) Ближе к ближайшей бонусной клетке — вперёд.
    if (a.weekDaysToBonus !== b.weekDaysToBonus) return a.weekDaysToBonus - b.weekDaysToBonus;
    // 3) Длиннее серия — вперёд.
    if (a.weekStreak !== b.weekStreak) return b.weekStreak - a.weekStreak;
    // 4) Давно не братые — вперёд (как было до 11.11).
    if (a.usedAt === null && b.usedAt === null) return a.id - b.id;
    // Никогда не использованный — раньше использованных.
    if (a.usedAt === null) return -1;
    if (b.usedAt === null) return 1;
    if (a.usedAt !== b.usedAt) return a.usedAt < b.usedAt ? -1 : 1;
    return a.id - b.id;
  });
}

/**
 * Разбиение списка на экране (заказ владельца 04.11).
 *
 * - `next` — ОДИН аккаунт наверху: тот, чья следующая активация даст больше
 *   всего очков (клетка 4 или 7 → 1000), при равенстве — тот, до бонуса
 *   которого ближе. После его активации наверх встаёт следующий.
 * - `activated` — активированные, свежий сверху; по умолчанию показываются
 *   первые `ACTIVATED_PREVIEW_LIMIT`, остальные — по кнопке «показать все».
 * - `queued` — остальные свободные (в очереди за следующим).
 */
export type AccountSplit<T> = {
  /** Следующий свободный аккаунт — верхний слот. */
  next: T | null;
  /** Активированные, свежий сверху. */
  activated: T[];
  /** Остальные свободные — в очереди. */
  queued: T[];
};

export function splitAccounts<T extends AccountRotationRow>(
  accounts: T[],
  now: Date = new Date(),
): AccountSplit<T> {
  const sorted = sortAccounts(accounts, now);
  const free: T[] = [];
  const activated: T[] = [];
  for (const account of sorted) {
    // Исчерпанная неделя — тоже «вниз»: наверх такой аккаунт не встаёт
    // (заказ владельца 07.11), но он остаётся в списке со своей историей.
    if (isUnavailable(account, now)) activated.push(account);
    else free.push(account);
  }
  const [next, ...queued] = free;
  return { next: next ?? null, activated, queued };
}

/** Строка журнала активаций. */
export type UsageRow = {
  projectId: number | null;
  projectName: string | null;
  tokens: number;
};

/** Сводка по проекту: сколько активаций и сколько токенов. */
export type ProjectUsage = {
  projectId: number | null;
  projectName: string | null;
  activations: number;
  tokens: number;
};

/**
 * Свод по проектам: «на какой проект больше токенов». Считается по журналу
 * активаций, а не по текущему состоянию аккаунтов — иначе повторное
 * использование того же аккаунта затирало бы прошлый расход.
 *
 * Порядок — по токенам (главный вопрос владельца), при равенстве — по числу
 * активаций.
 */
export function aggregateUsage(rows: UsageRow[]): ProjectUsage[] {
  const byProject = new Map<number | null, ProjectUsage>();
  for (const row of rows) {
    const current = byProject.get(row.projectId) ?? {
      projectId: row.projectId,
      projectName: row.projectName,
      activations: 0,
      tokens: 0,
    };
    current.activations += 1;
    current.tokens += row.tokens;
    byProject.set(row.projectId, current);
  }
  return [...byProject.values()].sort(
    (a, b) => b.tokens - a.tokens || b.activations - a.activations || (a.projectName ?? '').localeCompare(b.projectName ?? ''),
  );
}
