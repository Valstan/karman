/**
 * Мультиаккаунт: правило простоя и порядок списка.
 *
 * Задача владельца (2026-11-03): аккаунты внешних сервисов, которыми он
 * переключается, пока программирует. Правило уточнено 04.11: активация
 * даёт аккаунту СВОИ часы простоя — от момента активации, а не до общей
 * полуночи по календарю. Активировали в 23:50 — аккаунт свободен в 05:50.
 *
 * С 07.11 окно простоя — **10 ЧАСОВ** (07.11 владелец просил 6 часов, 08.11
 * растянул до 10: «ну, давай до 10 часов, что ли, его растянем, потому что
 * иногда… некоторые токены приходят, уже активированы… то есть бонус ему не
 * дается»), с 11.11 — **5 ЧАСОВ** (столько же длится окно расхода у MiniMax),
 * а **с 15.11 — до ночного сброса** (см. ниже).
 *
 * ## Почему ночная граница, а не календарные сутки (мандат владельца 15.11)
 *
 * «Они запрашивают у тебя токен, входят с этим токеном в аккаунт… активирует
 * на нём очки… 1 раз в сутки активируется бонус, или 400 очков, или 1000
 * очков… если ты токен отдал его забрал один из проектов, то можешь его помечать
 * погашенным, израсходованным на следующие 24 часа. Но там единственный
 * вариант, что возможно, что все токены освобождаются ночью, может в 12 ночи,
 * может быть в 3 ночи, я не знаю точно».
 *
 * Суть: суточный бонус MiniMax даётся ОДИН раз в сутки, а момент сброса
 * лимита — ночью и в НЕИЗВЕСТНЫЙ час. Значит московская календарная дата для
 * «чек-ин уже был» — ненадёжная граница: аккаунт, активированный вчера в
 * 23:50, сегодня по календарю «не отмечен», а бонус у MiniMax ещё не сброшен —
 * потребитель получает «insufficient balance».
 *
 * Владелец спросил прямо: «а чо, вариант сброса аккаунтов ночью не
 * рассматриваешь совсем? вроде бывает такое, работаешь-работаешь на аккаунте и
 * бац в 12 часов смотришь — а у него снова можно очки активировать».
 * Рассматриваем: аккаунт сожжён не «24 часа от активации», а **до ближайшего
 * ночного сброса**.
 *
 * ## Какие часы сброса (данные, а не догадки)
 *
 * Час сброса владелец знает неточно («может в 12 ночи, может быть в 3 ночи»),
 * поэтому берём ОБА варианта и освобождаем аккаунт по **более позднему** из них:
 * ждать дольше всегда безопасно — к этому моменту бонус у MiniMax точно
 * обновился, и мы его не потратили.
 *
 * Что показали боевые данные (письмо Сарафана на линии, id 150 от 15.11 01:23,
 * плюс журнал выдач):
 *
 * - в 00:25–00:27 МСК пятнадцать аккаунтов подряд отказали сразу —
 *   «insufficient balance (1008)». Это ровно те аккаунты, что владелец
 *   активировал накануне (12:51–18:50): суточный бонус у них ещё НЕ обновился;
 * - в 06:17 и 07:43 МСК те же аккаунты бонус получили — и клетку 7, 1000 очков,
 *   что подтвердила уже панель MiniMax.
 *
 * Значит сброс случился между 00:27 и 06:17 МСК: в полночь его ещё не было.
 * Вариант «3 ночи» (03:00 МСК — это полночь UTC) в этот промежуток укладывается,
 * и именно он зашит в `DAILY_RESET_HOURS`.
 *
 * Итог: аккаунт, активированный в 03:00–24:00, свободен с 03:00 следующих
 * суток; активированный в 00:00–03:00 (неопределённая полоса) — с 00:00
 * следующих суток. Второй случай ждёт целые сутки — это цена того, что час
 * сброса неизвестен точно: ждать дольше безопасно, ждать меньше — нет.
 *
 * Что это меняет:
 *
 * - очки по-прежнему даёт ЕЖЕДНЕВНЫЙ чек-ин (раз в сутки на аккаунт), и
 *   ограничителем недели теперь стал не суточный инвариант, а **недельная
 *   квота в 7 активаций** (см. `lib/accounts/weekly.ts`): неделя у аккаунта
 *   своя — 7 дней от его ПЕРВОГО использования (так устроено окно MiniMax);
 * - журнал по-прежнему хранит ОДНУ строку на аккаунт на московские сутки:
 *   повторная активация того же дня обновляет строку дня, а не плодит вторую.
 *   Ночная граница этому не противоречит: освобождение всегда приходится на
 *   СЛЕДУЮЩИЕ московские сутки, поэтому две активации одного аккаунта в одни
 *   московские сутки по-прежнему невозможны. Поэтому ни одна миграция схемы
 *   для перехода окна 24 ч → 10 ч → 5 ч → ночной границы не понадобилась —
 *   менялось правило простоя, а не структура журнала;
 * - «отмечен сегодня по Москве» перестало быть границей: у доступного аккаунта
 *   этого поля быть не может (чек-ин сегодня ⇒ активация сегодня ⇒ сожжён до
 *   ночного сброса ⇒ недоступен). Граница одна — ночной сброс после активации;
 * - аккаунт, у которого неделя исчерпана (7 из 7), **не предлагается** для
 *   активации: он уходит вниз списка вместе с занятыми.
 *
 * Сессия активации: окно открывает явная кнопка «Активировать» (заказ владельца
 * 05.11: копирование почты или пароля аккаунт НЕ гасит). Пока сессия открыта,
 * повторная активация того же аккаунта её ПРОДОЛЖАЕТ: окно не сдвигается, в
 * журнале одна строка, поэтому статистика не удваивается.
 *
 * СУТОЧНЫЙ БОНУС, А НЕ ОКНО РАСХОДА: окно 24 часа было ещё и 18 часов
 * (проверено 06.11 по документации MiniMax) — тогда границей считали гарантию
 * «чек-ин в сутки один» (400 очков, в 4-й и 7-й дни — 1000). С 07.11 эту
 * гарантию закрыла недельная квота в 7 активаций, и окно можно было сокращать.
 * С 15.11 границу снова задаёт суточный бонус, но уже честно — по ночному
 * сбросу у MiniMax (подробности в docs/minimax.md).
 *
 * Порядок экрана (заказ владельца 04.11): наверху ОДИН аккаунт — тот, что
 * дольше всех не активировался (никогда не использованный — самый первый);
 * после его активации наверх встаёт следующий. Ниже — активированные, и чем
 * позже активирован, тем выше (свежий сверху).
 *
 * Никакой ночной задачи: доступность считается при чтении, поэтому аккаунт
 * сам становится свободным по истечении своего окна.
 *
 * Модуль чистый (без server-only и без БД) — юнит-тестируется.
 */

import { moscowLocalToUtcIso, utcToMoscowLocal } from '@/lib/reminders/time';
import { panelClaimable, panelClaimed } from '@/lib/minimax/panel';

/**
 * Часы ночного сброса суточного лимита MiniMax (московское время).
 *
 * Час сброса владелец знает неточно: «может в 12 ночи, может быть в 3 ночи»
 * (15.11). Поэтому берём ОБА варианта и освобождаем аккаунт по **более позднему**
 * из них: ждать дольше всегда безопасно — к этому моменту бонус у MiniMax точно
 * обновился, и мы его не потратили.
 *
 * Боевые данные сузили окно: в 00:25–00:27 МСК 15.11 пятнадцать аккаунтов,
 * активированных накануне, отказали сразу («insufficient balance (1008)») —
 * сброса в полночь ещё не было; в 06:17 и 07:43 те же аккаунты бонус получили
 * (клетка 7, 1000 очков — подтверждено панелью MiniMax). Значит сброс был
 * владельца «3 ночи».
 */
export const DAILY_RESET_HOURS = [0, 3] as const;

/**
 * Сдвиг московской даты 'YYYY-MM-DD' на N дней.
 */
function shiftMoscowDate(date: string, days: number): string {
  const ms = Date.UTC(
    Number(date.slice(0, 4)),
    Number(date.slice(5, 7)) - 1,
    Number(date.slice(8, 10)) + days,
  );
  return new Date(ms).toISOString().slice(0, 10);
}

/**
 * Ближайший безопасный ночной сброс после момента `at` — UTC-инстант.
 *
 * Для каждого часа-кандидата ищем ближайший сброс строго после `at`, потом
 * берём самый поздний из найденных: ждать дольше безопасно, ждать меньше —
 * нет (можно отдать аккаунт, чей бонус ещё не обновился).
 */
export function dailyResetAfter(at: Date, hours: readonly number[] = DAILY_RESET_HOURS): Date {
  const localDate = utcToMoscowLocal(at).slice(0, 10);
  const nextPerHour: number[] = [];
  for (const hour of hours) {
    const hh = String(hour).padStart(2, '0');
    // Ближайший сброс этого часа после `at`.
    let next = Number.POSITIVE_INFINITY;
    for (const dayOffset of [0, 1]) {
      const day = shiftMoscowDate(localDate, dayOffset);
      const ms = new Date(moscowLocalToUtcIso(`${day}T${hh}:00`)).getTime();
      if (ms > at.getTime() && ms < next) next = ms;
    }
    nextPerHour.push(next);
  }
  // Из всех вариантов сброса берём самый поздний.
  return new Date(Math.max(...nextPerHour));
}

/**
 * Когда суточный бонус аккаунта точно восстановится после активации в `usedAt`
 * (ISO) — или null, если аккаунт не активировался ни разу.
 */
export function bonusRestoredAt(usedAt: string | null): string | null {
  if (!usedAt) return null;
  return dailyResetAfter(new Date(usedAt)).toISOString();
}

/**
 * Отсечка по моменту активации: аккаунты, активированные СТРОГО раньше этого
 * момента, к `now` уже свободны (суточный бонус восстановился).
 *
 * Нужна для честного «занято» прямо в SQL: аккаунт считается свободным, только
 * если и midnight-кандидат, и 03:00-кандидат уже прошли. То есть берётся более
 * ранний из двух последних сбросов.
 */
export function freeBefore(now: Date, hours: readonly number[] = DAILY_RESET_HOURS): Date {
  const localDate = utcToMoscowLocal(now).slice(0, 10);
  const lastPerHour: number[] = [];
  for (const hour of hours) {
    const hh = String(hour).padStart(2, '0');
    let last = Number.NEGATIVE_INFINITY;
    for (const dayOffset of [0, -1]) {
      const day = shiftMoscowDate(localDate, dayOffset);
      const ms = new Date(moscowLocalToUtcIso(`${day}T${hh}:00`)).getTime();
      if (ms <= now.getTime() && ms > last) last = ms;
    }
    lastPerHour.push(last);
  }
  return new Date(Math.min(...lastPerHour));
}

