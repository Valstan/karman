/**
 * Статусы клетки панели MiniMax — общие для сервера и браузера.
 *
 * Ответ `GET /minimax-cloud/api/v1/signin/status` отдаёт круг из семи клеток
 * недельного цикла аккаунта; у каждой клетки свой статус:
 *
 * - **1** — день не начался (клетка впереди сегодняшней);
 * - **2** — **очки можно забрать прямо сейчас** (сегодняшняя клетка, бонус ждёт);
 * - **3** — очки забраны (сегодняшняя клетка уже использована);
 * - **4** — клетка недоступна.
 *
 * Живая проба 16.11 (аккаунты 48, 47 — активированы накануне): день 1 — status 3
 * (забрано), день 2 — status 2 (сегодня, можно забрать, 400 очков), дни 3–7 —
 * status 1 (не начались). Аккаунты, активированные сегодня (63, 85): день 1 —
 * status 3 (сегодня, забрано), дальше status 1.
 *
 * Значит у СЕГОДНЯШНЕЙ клетки бывает ровно два состояния: status 2 — очки
 * есть, status 3 — очки сожжены. Остальные статусы — это «не знаю»: по ним
 * протухшее состояние нельзя превращать в «очков нет».
 *
 * Модуль чистый — без БД, без server-only и без node-зависимостей, поэтому его
 * берут и серверные сервисы, и клиентские компоненты.
 */

/** День не начался. */
export const PANEL_STATUS_NOT_STARTED = 1;
/** Очки можно забрать прямо сейчас. */
export const PANEL_STATUS_CLAIMABLE = 2;
/** Очки забраны. */
export const PANEL_STATUS_CLAIMED = 3;
/** Клетка недоступна. */
export const PANEL_STATUS_UNAVAILABLE = 4;

/** «Очки можно забрать прямо сейчас» — по статусу клетки. */
export function panelClaimable(status: number | null | undefined): boolean {
  return status === PANEL_STATUS_CLAIMABLE;
}

/** «Очки сожжены» — по статусу клетки. */
export function panelClaimed(status: number | null | undefined): boolean {
  return status === PANEL_STATUS_CLAIMED;
}

/**
 * Пояс владельца: панель программирования — это комп владельца.
 */
export const OWNER_TIMEZONE = 'Europe/Moscow';

/**
 * Пояс по умолчанию для потребителя — «поздний» из двух возможных.
 *
 * Сутки MiniMax считаются по поясу запроса, поэтому в полночь МСК один и тот же
 * аккаунт для панели владельца (Europe/Moscow) уже «завтрашний», а для потребителя
 * на UTC — ещё «сегодняшний» (его сутки сменятся в 03:00 МСК). Для выдачи
 * берём ПОЗДНИЙ пояс: тогда очки гарантированно есть у обеих сторон.
 */
export const DEFAULT_TIMEZONE = 'UTC';

/** Пояс потребителя по комнате: панель программирования — это комп владельца. */
export function timezoneForRoom(roomSlug: string): string {
  if (roomSlug === 'brain') return OWNER_TIMEZONE;
  return DEFAULT_TIMEZONE;
}
