/**
 * Разбор `Authorization: Bearer …` для машинного доступа к vault.
 *
 * ## Зачем общий модуль (R2, Q3-самоосмотр 2026-08-10)
 *
 * Пять роутов `/api/secrets*` носили **копию одной и той же** функции `bearerToken`:
 * `secrets`, `secrets/session`, `secrets/claim`, `secrets/self`, `secrets/provision`.
 * Пять мест — значит правка контракта разъезжается молча: правили один, а на бою
 * оставались четыре старых, и отказ приходил туда, где его не ждали.
 *
 * Родственник на полпути: `clientIp` уехал в `lib/api/client-ip.ts` (аудит #057, R1)
 * — там копий не осталось, потому что правило живёт в одном файле, а проверка
 * живого контракта — в тесте рядом.
 *
 * ## Контракт (перенесён как есть — поведение всех пяти копий было ровно таким)
 *
 * - схема `Bearer` нечувствительна к регистру (`/i`);
 * - между схемой и токеном — один или больше пробельных символов (`\s+`);
 * - токен обрезается по краям; пустой → `null`;
 * - заголовка нет, он пустой, схема другая или токена нет → `null`;
 * - значение после схемы берётся **как есть**: `Bearer a b` даст токен `a b`.
 *   Такой токен не совпадёт ни с одной комнатой — это 401, а не обход. Менять
 *   это здесь означало бы менять контракт, а не выносить его.
 */
export function bearerToken(req: Request): string | null {
  const m = /^Bearer\s+(.+)$/i.exec((req.headers.get('authorization') ?? '').trim());
  const token = m?.[1]?.trim();
  return token ? token : null;
}
