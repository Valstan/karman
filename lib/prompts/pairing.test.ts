import { describe, expect, it } from 'vitest';

import {
  citedIds,
  citedPlanIds,
  isPlanTitle,
  mergePromptBodies,
  quotedPromptId,
  titleOverlapWords,
} from './pairing';

/**
 * Пара «начитка + план» в хранилище промтов (заказ владельца 24.11).
 *
 * Правила здесь осторожные по одной причине: приклеить план ЧУЖОЙ задачи —
 * хуже, чем показать лишнюю запись. Поэтому каждый признак проверяется
 * отдельно, а «не уверен» означает «не сливать».
 */
describe('пара «начитка + план»', () => {
  it('план узнаётся по заголовку, а «Планшет» — нет', () => {
    expect(isPlanTitle('План: ПП — нумерация по контракту')).toBe(true);
    expect(isPlanTitle('План (дополнение): печать картинок')).toBe(true);
    expect(isPlanTitle('План (v2): Локальный MiniMax')).toBe(true);
    expect(isPlanTitle('План')).toBe(true);
    // Начитки владельца, которые начинаются так же.
    expect(isPlanTitle('Планшет: беда с доступом')).toBe(false);
    expect(isPlanTitle('Планшетная версия Матрицы РМЗ')).toBe(false);
    expect(isPlanTitle('Производственная программа: поля ввода')).toBe(false);
    expect(isPlanTitle('ПП: добавить двигатели списком')).toBe(false);
  });

  it('ссылки на записи читаются в обеих формах', () => {
    expect(citedIds('Уточнение к плану id 55')).toEqual([55]);
    expect(citedIds('план владельца (запись #125) и промт #124')).toEqual([125, 124]);
    expect(citedIds('план — id 62, ответы — id 61')).toEqual([62, 61]);
    expect(citedIds('просто текст без ссылок')).toEqual([]);
  });

  it('ссылка на план отличается от прочей ссылки на запись', () => {
    expect(citedPlanIds('Ответы владельца 21.11 по плану id 65')).toEqual([65]);
    expect(citedPlanIds('Уточнение к плану id 55')).toEqual([55]);
    expect(citedPlanIds('промт #124')).toEqual([]);
    // «план владельца 24.11.2026» — не ссылка на запись: именительный падеж.
    expect(citedPlanIds('план владельца 24.11.2026 «Планшет — доступ» (запись #113)')).toEqual([]);
  });

  it('заголовки сравниваются по смыслу, а не по буквам', () => {
    const план = 'План: колонка «Привязка» — короткий номер договора и номер ДС';
    const начитка = 'Колонка «Привязка»: три цифры договора вместо слова «договор», номер ДС';
    expect(titleOverlapWords(план, начитка)).toBeGreaterThanOrEqual(2);
    expect(titleOverlapWords('План: ПП на планшете — разобрать, чем срезан раздел',
      'Планшет: раздел «Производственная программа» не появился в меню')).toBeGreaterThanOrEqual(2);
    expect(titleOverlapWords('План: печатные формы', 'Список двигателей: группировка')).toBe(0);
  });

  it('дословная цитата начитки узнаётся', () => {
    const начитка = {
      id: 104,
      body: 'Вывод ПП в разные места идёт по-разному: если в Excel — двойная нумерация, общая и по контракту, сохраняется, а если на печать выводишь — нумерации по контрактам пропадает.',
    };
    const план = `> **Основание:** промт владельца: «${начитка.body}»`;
    expect(quotedPromptId(план, [начитка])).toBe(104);
    // Чужая начитка цитатой не считается.
    expect(quotedPromptId(план, [{ id: 7, body: 'Совсем другой текст без цитаты' }])).toBeNull();
  });

  it('слитые тела: начитка, пустая строка, план', () => {
    expect(mergePromptBodies('Начитка', 'План')).toBe('Начитка\n\nПлан');
    expect(mergePromptBodies('Начитка', '  ')).toBe('Начитка');
    expect(mergePromptBodies('', 'План')).toBe('План');
  });
});
