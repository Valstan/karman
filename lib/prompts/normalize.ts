/**
 * Детерминированная часть причёмы надиктованного промта.
 *
 * Здесь только то, что можно решить без модели: переводы строк, висячие
 * пробелы, пустые строки, заголовок из первой строки. Всё остальное (смысл,
 * опечатки, пунктуация, «убери слова-паразиты») — работа Мозга, и он приносит
 * уже причёсанный текст; правило «минимально-достаточная правка» описано в
 * `.claude/commands/prompts.md` канона Мозга.
 *
 * Модуль чистый: без БД и без server-only — его можно тестировать как есть.
 */

/** Потолок длины промта. Длиннее — это уже не промт, а документ. */
export const MAX_PROMPT_LENGTH = 20_000;

/** Потолок длины заголовка (совпадает с шириной колонки `prompt.title`). */
export const MAX_PROMPT_TITLE_LENGTH = 200;

/**
 * Приводит текст промта к единому виду: CRLF → LF, без BOM, без висячих
 * пробелов в конце строк, не больше одной пустой строки подряд, без хвостовых
 * пустых строк.
 *
 * Смысл текста не трогает — ни одного символа, кроме пробельных, отсюда не
 * уходит. Поэтому промт, надиктованный «как есть», и промт, причёсанный
 * Мозгом, отличаются только словами, а не формой.
 */
export function normalizePromptText(raw: string): string {
  return raw
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/**
 * Заголовок для списка: первая непустая строка, обрезанная до 200 символов.
 *
 * Если промт начинается со строки заголовка («Напиши текст для…») — это и
 * будет его имя в списке. Если строки-заголовка нет, берётся первая строка
 * текста: длиннее первой строки заголовок всё равно не информативнее.
 */
export function derivePromptTitle(body: string): string {
  const first = body.split('\n').find((line) => line.trim().length > 0)?.trim() ?? '';
  if (first.length <= MAX_PROMPT_TITLE_LENGTH) {
    return first;
  }
  return `${first.slice(0, MAX_PROMPT_TITLE_LENGTH - 1).trimEnd()}…`;
}
