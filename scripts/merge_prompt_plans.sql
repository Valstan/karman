-- Слияние пар «начитка + план» в один промт (заказ владельца 24.11).
--
-- Что делает: в хранилище промтов Мозг складывал надиктованную задачу («начитка») и
-- план к ней ДВУМЯ записями. По заказу владельца пара должна лежать ОДНИМ текстом,
-- ОДНИМ промтом: тело начитки, пустая строка, тело плана. Продолжения задачи
-- («Уточнение к плану id 55», «Ответы владельца по плану id 65») и дополнения
-- («План (дополнение): …») присоединяются к своей паре в том же порядке.
--
-- Карта пар — проверенная по живому хранилищу (заголовки + цитаты в текстах):
--   - начитка и план лежат рядом и называются одной темой;
--   - продолжение прямо цитирует план по id («плану id 55»);
--   - дополнение цитирует пару («запись #125» и «промт #124») или дословно
--     цитирует начитку.
--
-- Продублированная задача («ПП: поля налезают друг на друга», 23.11 и 24.11):
-- начитки побайтово одинаковы (md5 совпадает), планы разные — старый подробный и
-- позднее уточнение «правка уже в main». Оставлен ОДИН промт (id 86) с обоими
-- планами: ничего не теряется, задача в хранилище одна.
--
-- Дубль «МиниГен: вкладка "Агенты"» (id 122 и 123, тела идентичны) схлопнут в один.
--
-- Откат: дамп таблиц prompt и prompt_project перед слиянием —
--   sudo -n -u postgres pg_dump -d karman_db -t prompt -t prompt_project \
--     --data-only -f /tmp/prompt_before_merge_20261124.sql
--
-- Слияние идёт в одной транзакции: ON_ERROR_STOP=1 — оборванная транзакция
-- откатывается целиком.

BEGIN;

-- 1. Дописать части (планы, продолжения, дополнения) к их начиткам.
WITH parts(prompt_id, ord, part_id) AS (
  VALUES
    (4, 1, 5), (6, 1, 7), (8, 1, 12), (9, 1, 13), (10, 1, 14), (11, 1, 15),
    (16, 1, 17), (18, 1, 19), (20, 1, 25), (21, 1, 26), (22, 1, 27), (23, 1, 28),
    (24, 1, 29), (30, 1, 31), (32, 1, 33), (34, 1, 35), (36, 1, 37), (38, 1, 39),
    (40, 1, 41), (42, 1, 43), (44, 1, 45), (46, 1, 47), (48, 1, 49), (50, 1, 51),
    (52, 1, 53), (54, 1, 55), (54, 2, 58), (56, 1, 57), (59, 1, 60), (61, 1, 62),
    (61, 2, 63), (64, 1, 65), (64, 2, 66), (67, 1, 68), (67, 2, 69), (70, 1, 71),
    (72, 1, 73), (74, 1, 75), (76, 1, 77), (78, 1, 79), (82, 1, 83), (84, 1, 85),
    (86, 1, 81), (86, 2, 87), (88, 1, 89), (88, 2, 102), (90, 1, 91), (92, 1, 93),
    (94, 1, 95), (96, 1, 97), (98, 1, 99), (100, 1, 101), (103, 1, 107),
    (104, 1, 108), (105, 1, 109), (106, 1, 110), (111, 1, 113), (111, 2, 115),
    (112, 1, 114), (116, 1, 117), (118, 1, 119), (120, 1, 121), (124, 1, 125),
    (124, 2, 128), (126, 1, 127)
), merged AS (
  SELECT p.prompt_id, string_agg(pr.body, E'\n\n' ORDER BY p.ord) AS addition
  FROM parts p
  JOIN prompt pr ON pr.id = p.part_id
  GROUP BY p.prompt_id
)
UPDATE prompt t
SET body = t.body || E'\n\n' || m.addition
FROM merged m
WHERE t.id = m.prompt_id;

-- 2. Убрать слитые записи: планы, продолжения, дополнения и продублированную начитку.
DELETE FROM prompt
WHERE id IN (
  5, 7, 12, 13, 14, 15, 17, 19, 25, 26, 27, 28, 29, 31, 33, 35, 37, 39, 41,
  43, 45, 47, 49, 51, 53, 55, 57, 58, 60, 62, 63, 65, 66, 68, 69, 71, 73, 75,
  77, 79, 80, 81, 83, 85, 87, 89, 91, 93, 95, 97, 99, 101, 102, 107, 108, 109,
  110, 113, 114, 115, 117, 119, 121, 123, 125, 127, 128
);

COMMIT;
